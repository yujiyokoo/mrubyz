// Tiny mrubyz test program for the TI-84 Plus (z88dk +ti83p, plain TI-OS).
// Runs the demo/add.rb bytecode (a = 2; b = 4; c = a + b) and shows c.
#include <stdio.h>
#include <stdlib.h>
#include <stdint.h>
#include <malloc.h>
#include "mrubyz.h"

// Heap owned by this program. The linker reserves the full array, so the
// allocator cannot hand out memory that belongs to TI-OS.
// Do not copy the `long _heap; sbrk(&_heap, 4096)` trick from demo01.c.
static uint8_t heap[2048];

// The read_bytecode builtin in mrubyz.c calls this. This demo does not use it.
uint8_t bytecode_at(uint8_t i) {
  (void)i;
  return 0;
}

// Defined in demo/add.ruby.c (generated by mrbc from demo/add.rb).
extern const uint8_t bytecode[];

void main() {
  mrbz_val v;
  mrbz_vm vm;

  mallinit();
  sbrk(heap, sizeof(heap));

  printf("mruby on TI-84 Plus\n");
  printf("a=2 b=4 c=a+b\n");

  mrbz_vm_run(&vm, &v, bytecode);

  printf("returned: %d\n", v.u.intval);
  printf("press a key\n");
  fgetc_cons();
}
