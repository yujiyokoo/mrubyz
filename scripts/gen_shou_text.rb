#!/usr/bin/env ruby
# frozen_string_literal: true

# Generate the demo07 whiteout message tiles ("KANSAI RUBYKAIGI9") as a
# C header, one 8x8 tile per message character (in message order, so the
# runtime reveals letter i by writing tile SHOU_CIRCLE_TILE_COUNT + i).
#
# Strokes use BG palette index 15: the circle only uses indices 0-12 and
# the light show never touches 13-15, so the text stays black even during
# the whiteout. Empty pixels are index 0 (white while whited out).
#
# Usage: ruby scripts/gen_shou_text.rb FONT8.BIN demo/shou_text.h

require_relative 'font_builder'

module ShouText
  MESSAGE = 'KANSAI RUBYKAIGI9'

  # [8 glyph row bytes] -> 32 bytes 4bpp planar. Stroke index 15 = 0b1111,
  # so each row byte lands verbatim in all four bitplanes.
  def self.encode_tile(rows8)
    rows8.flat_map { |b| [b, b, b, b] }
  end

  def self.generate(font_bin_path, out_path)
    glyphs = FontBuilder.parse_standard_font_bin(File.binread(font_bin_path))
    bytes = MESSAGE.chars.flat_map { |ch| encode_tile(glyphs[ch.ord]) }

    File.open(out_path, 'w') do |f|
      f.puts '// Auto-generated by scripts/gen_shou_text.rb — do not edit'
      f.puts "// One tile per character of \"#{MESSAGE}\", strokes = BG palette index 15."
      f.puts '// Load at VRAM SHOU_CIRCLE_TILE_COUNT; reveal_letter(i) writes tile base+i.'
      f.puts 'const unsigned char shou_text_tiles[] = {'
      bytes.each_slice(16) { |s| f.puts '  ' + s.map { |b| '0x%02x' % b }.join(', ') + ',' }
      f.puts '};'
    end

    defs_path = out_path.sub(/\.h\z/, '_defs.h')
    File.open(defs_path, 'w') do |f|
      f.puts '// Auto-generated by scripts/gen_shou_text.rb — do not edit'
      f.puts "#define SHOU_TEXT_LEN #{MESSAGE.length}"
    end

    puts "Generated #{out_path} (+ #{defs_path}): #{MESSAGE.length} tiles, #{bytes.length} bytes"
  end
end

if __FILE__ == $0
  abort "Usage: ruby #{$0} <FONT8.BIN> <output.h>" unless ARGV[1]
  ShouText.generate(ARGV[0], ARGV[1])
end
